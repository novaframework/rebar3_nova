-module(rebar3_nova_release_SUITE).

-include_lib("common_test/include/ct.hrl").
-include_lib("stdlib/include/assert.hrl").

-export([all/0, suite/0, init_per_suite/1]).
-export([
    release_leaves_the_openapi_spec_alone/1
]).

-define(SPEC, ~"{\"openapi\": \"generated by the app\"}\n").

%% Needs rebar3 on PATH and hex.pm reachable.

suite() ->
    [{timetrap, {minutes, 15}}].

all() ->
    [
        release_leaves_the_openapi_spec_alone
    ].

init_per_suite(Config) ->
    case os:find_executable("rebar3") of
        false ->
            {fail, "rebar3 is not on PATH"};
        Rebar3 ->
            App = fixture(?config(priv_dir, Config)),
            ok = rebar3(Rebar3, App, ["nova", "release"]),
            [{app, App} | Config]
    end.

%% `priv/assets` is served publicly; a spec the app generates with its own
%% options must survive a release.
release_leaves_the_openapi_spec_alone(Config) ->
    ?assertEqual(
        {ok, ?SPEC},
        file:read_file(filename:join([?config(app, Config), "priv", "assets", "openapi.json"]))
    ).

fixture(PrivDir) ->
    App = filename:join(PrivDir, "tpl"),
    Files = [
        {"rebar.config", fixture_rebar_config()},
        {"src/tpl.app.src",
            "{application, tpl, [{vsn, \"0.1.0\"}, {registered, []},\n"
            " {applications, [kernel, stdlib, nova]}, {env, []}]}.\n"},
        {"src/tpl_router.erl",
            "-module(tpl_router).\n-export([routes/1]).\n"
            "routes(_Env) ->\n"
            "    [#{prefix => \"\", security => false,\n"
            "       routes => [{\"/hello\", fun tpl_controller:hello/1, #{methods => [get]}}]}].\n"},
        {"src/tpl_controller.erl",
            "-module(tpl_controller).\n-export([hello/1]).\n"
            "hello(_Req) -> {status, 200}.\n"},
        {"src/views/tpl_hello.dtl", "Hello {{ name }}\n"},
        {"priv/schemas/hello.json", "{\"type\": \"object\"}\n"},
        {"priv/assets/openapi.json", ?SPEC}
    ],
    [ok = write(filename:join(App, Path), Content) || {Path, Content} <- Files],
    Plugin = filename:join([App, "_checkouts", "rebar3_nova"]),
    [ok = copy(repo_path(Name), filename:join(Plugin, Name)) || Name <- plugin_files()],
    App.

fixture_rebar_config() ->
    "{erl_opts, [debug_info]}.\n"
    "{deps, [{nova, \"0.18.1\"}]}.\n"
    "{overrides, [{override, cowboy, [{deps, [{cowlib, \"2.19.0\"}, {ranch, \"2.2.0\"}]}]}]}.\n"
    "{erlydtl_opts, [{doc_root, \"src/views\"}]}.\n"
    "{project_plugins, [{rebar3_erlydtl_plugin, \"0.1.1\"}, rebar3_nova]}.\n"
    "{provider_hooks, [{pre, [{compile, {erlydtl, compile}}]}]}.\n"
    "{relx, [{release, {tpl, \"0.1.0\"}, [tpl]}, {mode, dev}]}.\n"
    "{profiles, [{prod, [{relx, [{mode, prod}, {include_erts, false}]}]}]}.\n".

plugin_files() ->
    ["rebar.config", "rebar.lock", "src", "priv"].

rebar3(Rebar3, Dir, Args) ->
    Port = open_port(
        {spawn_executable, Rebar3},
        [
            {args, Args},
            {cd, Dir},
            {env, [{"REBAR_GLOBAL_CONFIG_DIR", "no_global_config"}]},
            exit_status,
            stderr_to_stdout,
            binary
        ]
    ),
    {Status, Output} = collect(Port, []),
    ct:log("rebar3 ~ts (exit ~p):~n~ts", [lists:join(" ", Args), Status, Output]),
    case Status of
        0 -> ok;
        _ -> ct:fail({rebar3_failed, Args, Status})
    end.

collect(Port, Acc) ->
    receive
        {Port, {data, Data}} -> collect(Port, [Acc, Data]);
        {Port, {exit_status, Status}} -> {Status, Acc}
    end.

write(Path, Content) ->
    ok = filelib:ensure_dir(Path),
    file:write_file(Path, Content).

-spec copy(file:filename_all(), file:filename_all()) -> ok.
copy(From, To) ->
    case filelib:is_dir(From) of
        true ->
            {ok, Names} = file:list_dir(From),
            [ok = copy(filename:join(From, Name), filename:join(To, Name)) || Name <- Names],
            ok;
        false ->
            ok = filelib:ensure_dir(To),
            {ok, _} = file:copy(From, To),
            ok
    end.

repo_path(Name) ->
    filename:join([lib_dir(), "..", "..", "..", "..", Name]).

lib_dir() ->
    case code:lib_dir(rebar3_nova) of
        Dir when is_list(Dir) -> Dir
    end.
